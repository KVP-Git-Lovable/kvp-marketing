export const getObject = (key: string) => REPORT_OBJECTS.find((o) => o.key === key);

export const getFieldLabel = (objectKey: string, fieldKey: string) =>
  getObject(objectKey)?.fields.find((f) => f.key === fieldKey)?.label ?? fieldKey;

export const getMeasure = (objectKey: string, measureKey: string) =>
  getObject(objectKey)?.measures.find((m) => m.key === measureKey);
